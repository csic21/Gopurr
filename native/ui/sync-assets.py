#!/usr/bin/env python3
"""Generate NSH tokens and copy brand assets from Gopurr's shared sources."""

from pathlib import Path
import json
import re
import shutil

UI = Path(__file__).resolve().parent
ROOT = UI.parents[1]
manifest_path = UI / "nsh.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
manifest["version"] = json.loads((ROOT / "mygo.json").read_text(encoding="utf-8"))["version"]
manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
SOURCE = (ROOT / "internal/app/theme.go").read_text(encoding="utf-8")
FIELDS = {
    "Bg": "bg", "Side": "side", "Surface": "surface", "Hover": "hover",
    "Border": "border", "Selected": "selected", "SelectedBorder": "selectedBorder",
    "Text": "text", "Muted": "muted", "Faint": "faint", "Accent": "accent",
    "AccentText": "accentText", "AccentHover": "accentHover", "AccentPressed": "accentPressed",
    "Up": "up", "Down": "down", "Danger": "danger", "Warn": "warn",
    "Success": "success", "Grid": "grid",
}

lines = [
    '// Generated by sync-assets.py from internal/app/theme.go. Do not edit.',
    'import { colorScheme } from "nsh";',
    '',
]
for name in ("light", "dark"):
    match = re.search(rf"var {name}Palette = palette\{{(.*?)\n\}}", SOURCE, re.S)
    if not match:
        raise SystemExit(f"Missing {name}Palette in internal/app/theme.go")
    values = dict(re.findall(r'(\w+):\s+ui\.Hex\("(#[0-9a-fA-F]{6})"\)', match[1]))
    missing = FIELDS.keys() - values.keys()
    if missing:
        raise SystemExit(f"Unrecognized {name} palette fields: {sorted(missing)}")
    lines.append(f"export const {name} = {{")
    lines.extend(f'  {key}: "{values[field]}",' for field, key in FIELDS.items())
    lines.extend(["};", ""])
lines.append('export function colors() { return colorScheme() === "dark" ? dark : light; }')
lines.append("")
(UI / "src/theme.ts").write_text("\n".join(lines), encoding="utf-8", newline="\n")

assets = UI / "assets"
(assets / "icons").mkdir(parents=True, exist_ok=True)
shutil.copyfile(ROOT / "internal/brand/icon-master.png", assets / "icon-master.png")
shutil.copyfile(ROOT / "internal/brand/sidebar.png", assets / "sidebar.png")
for icon in (
    "layout-dashboard.svg", "file-text.svg", "globe.svg", "settings-2.svg",
    "circle-check.svg", "check.svg", "circle.svg", "arrow-up-right.svg", "arrow-down-left.svg",
    "shield-check.svg", "LICENSE",
    "cable.svg", "layers-2.svg", "list-filter.svg", "network.svg",
    "panel-left.svg", "square-terminal.svg",
):
    shutil.copyfile(ROOT / "internal/app/icons" / icon, assets / "icons" / icon)
